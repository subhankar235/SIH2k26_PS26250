"""WebSocket broadcaster for streaming live MAGI agent thought logs."""

import json
from typing import List
from fastapi import WebSocket


class MagiStreamManager:
    """Manages active WebSocket client connections and broadcasts live negotiation events."""

    def __init__(self):
        self.active_connections: List[WebSocket] = []

    async def connect(self, websocket: WebSocket) -> None:
        await websocket.accept()
        self.active_connections.append(websocket)

    def disconnect(self, websocket: WebSocket) -> None:
        if websocket in self.active_connections:
            self.active_connections.remove(websocket)

    async def broadcast(self, message: dict) -> None:
        """Broadcast live event to all connected dashboard clients."""
        payload = json.dumps(message)
        dead_connections = []
        for connection in self.active_connections:
            try:
                await connection.send_text(payload)
            except Exception:
                dead_connections.append(connection)

        for dead in dead_connections:
            self.disconnect(dead)


stream_manager = MagiStreamManager()


from pathlib import Path
from playwright.sync_api import sync_playwright, expect
BASE='http://localhost:3100'
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='msedge')
    page=browser.new_page(viewport={'width':1440,'height':950})
    errors=[];requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url) if ':8000' in r.url else None)
    def go(path):
        page.goto(BASE+path,wait_until='networkidle')
        expect(page.locator('.demo-workspace-note')).to_be_visible()
        expect(page.locator('.request-failure')).to_have_count(0)
    for path in ['/','/ingestion','/evidence','/evidence/ISSUE-01','/validity','/validity/DEC-802','/forecasts','/planning','/planning/compare','/stress-lab','/stress-lab/RUN-42','/explanations','/approvals','/audit','/benchmarks']:
        go(path)
        expect(page.locator('h1')).to_be_visible()
    go('/forecasts')
    page.get_by_label('Forecast scenario').select_option('FORECAST-02')
    expect(page.get_by_role('alert').filter(has_text='High uncertainty')).to_be_visible()
    go('/validity/DEC-802')
    page.get_by_role('button',name='Re-verify',exact=True).click()
    expect(page.get_by_text('verified',exact=True).first).to_be_visible()
    page.reload(wait_until='networkidle')
    expect(page.get_by_text('verified',exact=True).first).to_be_visible()
    go('/planning/compare')
    expect(page.locator('p[role="status"]')).to_contain_text('1 added, 1 removed')
    go('/planning')
    expect(page.get_by_text('TSK-100',exact=True).first).to_be_visible()
    page.get_by_role('button',name='Run Optimisation').click()
    page.wait_for_function("JSON.parse(localStorage.getItem('air-power-demo-v1')).schedules.length === 5")
    go('/stress-lab')
    page.get_by_label('Seed',exact=True).fill('0')
    page.get_by_role('button',name='Launch stress run').click()
    expect(page.locator('p[role="status"]')).to_contain_text('completed',timeout=12000)
    go('/explanations')
    page.get_by_label('Agent question').fill('Explain the capacity conflict')
    page.get_by_role('button',name='Ask Agent').click()
    page.wait_for_function("JSON.parse(localStorage.getItem('air-power-demo-v1')).agents.length === 2")
    page.wait_for_function("JSON.parse(localStorage.getItem('air-power-demo-v1')).agents[0].status === 'completed'",timeout=12000)
    go('/approvals')
    page.get_by_role('listitem').filter(has_text='SCH-843').get_by_role('button',name='Review',exact=True).click()
    expect(page.get_by_role('button',name='Approve Result')).to_be_disabled()
    page.get_by_role('button',name='Close review').click()
    page.get_by_role('listitem').filter(has_text='SCH-842').get_by_role('button',name='Review',exact=True).click()
    page.get_by_label('Reviewer name',exact=True).fill('Demo Analyst')
    page.get_by_label('Decision rationale',exact=True).fill('Evidence and capacity constraints reviewed')
    page.get_by_role('button',name='Approve Result').click()
    expect(page.get_by_label('Decision rationale',exact=True)).to_have_count(0)
    go('/audit')
    expect(page.get_by_text('Demo Analyst',exact=True)).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    go('/')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),'Mobile overflow'
    Path('frontend/test-results').mkdir(exist_ok=True)
    page.screenshot(path='frontend/test-results/demo-mobile.png',full_page=True)
    page.set_viewport_size({'width':1591,'height':960})
    page.screenshot(path='frontend/test-results/demo-dashboard.png',full_page=True)
    page.get_by_role('button',name='Workspace settings').click()
    page.get_by_role('button',name='Reset demo data',exact=True).click()
    page.wait_for_function("JSON.parse(localStorage.getItem('air-power-demo-v1'))?.schedules.length === 4")
    assert not requests,requests
    assert not errors,errors
    browser.close()
    print('PASS: 15 demo routes; forecast warning; persistent reverify; solve; preloaded diff; stress/agent polling; approval gate and audit; reset; mobile; no backend requests or browser errors.')
